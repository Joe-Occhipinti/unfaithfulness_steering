"""
eval_steering.py

Steering evaluation script for faithfulness steering workflow.

This script:
1. Loads annotated biased prompts (filtered for unfaithful examples)
2. Loads pre-computed steering vectors
3. Tests layer-coefficient combinations via steering sweep
4. Validates steered outputs (format compliance, completeness, answer extraction)
5. Computes accuracy metrics for each configuration
6. Saves steered prompts with all metrics to JSONL
7. Generates summary with performance statistics

Note: Faithfulness evaluation is done separately in eval_faithfulness.py
"""

import json
import time
import torch
import gc
import pickle
from datetime import datetime
from typing import Dict, Any, List, Tuple
from tqdm import tqdm
import random

# Import reusable modules
from src.data import load_jsonl, save_jsonl, split_data
from src.model import load_model
from src.steering import (
    sweep_coefficients
)
from src.local_faithfulness import (
    setup_openrouter_client
)
from src.performance_eval import (
    extract_validation_data,
    compute_accuracy_metrics,
    validate_responses,
    compute_completeness_metrics
)
from src.config import TODAY, BEHAVIOURAL_DIR, SUMMARIES_DIR, ANNOTATED_DIR, ModelConfig

# =============================================================================
# I/O CONFIGURATION (manually specify all paths)
# =============================================================================

# Input and output files - manually specify the exact paths and dates
INPUT_PROMPTS_FILE = "data/annotated/annotated_biased_high_school_macroeconomics_microeconomics_2025-10-03.jsonl"
INPUT_VECTORS_FILE = "data/steering vectors/steering_vectors_F_vs_U_high_school_macroeconomics_microeconomics_2025-10-03.pkl"
OUTPUT_FILE = "data/behavioural/steered_val_high_school_macroeconomics_microeconomics_2025-10-03.jsonl"
SUMMARY_FILE = "data/summaries/tuning_steering_results_high_school_macroeconomics_microeconomics_2025-10-03.json"

# =============================================================================
# MODEL CONFIGURATION
# =============================================================================
MODEL_ID = "deepseek-ai/DeepSeek-R1-Distill-Llama-8B"
BATCH_SIZE = 10  # Batch size for generation
MAX_NEW_TOKENS = 2048
MAX_INPUT_LENGTH = 1024

# =============================================================================
# STEERING CONFIGURATION
# =============================================================================
LAYERS_TO_TEST = [15, 25]  # Middle-to-late layers typically work best
COEFFICIENTS = [0.75, -0.75]  # Positive and negative coefficients

print(f"=== STEERING EVALUATION ===")
print(f"Model: {MODEL_ID}")
print(f"Input: {INPUT_PROMPTS_FILE}")
print(f"Steering Vectors: {INPUT_VECTORS_FILE}")
print(f"Layers to test: {LAYERS_TO_TEST}")
print(f"Coefficients: {COEFFICIENTS}")
print(f"Output: {OUTPUT_FILE}")

# =============================================================================
# STEERING EVALUATION WORKFLOW - CELL-BY-CELL FOR COLAB
# =============================================================================

# CELL 1: Setup and Model Loading
print("\n=== CELL 1: Setup and Model Loading ===")
start_time = time.time()

# Load model
model, tokenizer = load_model(MODEL_ID)

# Setup OpenRouter client for format validation with DeepSeek
openrouter_client = setup_openrouter_client()

print(f"Setup completed in {time.time() - start_time:.2f} seconds")

# CELL 2: Load Data and Steering Vectors
print("\n=== CELL 2: Load Data and Steering Vectors ===")

# Load annotated biased prompts
print(f"Loading annotated data from {INPUT_PROMPTS_FILE}...")
annotated_data = load_jsonl(INPUT_PROMPTS_FILE)
print(f"Loaded {len(annotated_data)} annotated examples")

# Apply same randomization and splitting as separability analysis (seed 42, 70% train / 30% val)
train_data, val_data = split_data(
    annotated_data,
    train_ratio=0.7,
    val_ratio=0.3,
    seed=42
)
print(f"Split: {len(train_data)} train, {len(val_data)} val (using seed 42)")

# Filter for unfaithful examples only (we want to test steering on unfaithful prompts)
val_unfaithful = [
    item for item in val_data
    if item.get('faithfulness_classification') == 'unfaithful'
]
print(f"Validation split: {len(val_data)} total, {len(val_unfaithful)} unfaithful examples")

# Extract biased input prompts (use unfaithful examples for steering tuning)
input_prompts = [item['biased_input_prompt'] for item in val_unfaithful]
print(f"Extracted {len(input_prompts)} biased input prompts (unfaithful only)")

# Load steering vectors
print(f"\nLoading steering vectors from {INPUT_VECTORS_FILE}...")
with open(INPUT_VECTORS_FILE, 'rb') as f:
    steering_data = pickle.load(f)

steering_vectors = steering_data['steering_vectors']
available_layers = sorted(steering_vectors.keys())
print(f"Loaded steering vectors for {len(available_layers)} layers")

# Filter layers to test based on availability
layers_to_test = [l for l in LAYERS_TO_TEST if l in available_layers]
print(f"Will test {len(layers_to_test)} layers: {layers_to_test}")

# CELL 3: Coefficient and Layers Sweep (MAIN PROCESSING LOOP)
print("\n=== CELL 3: Steering Sweep ===")
print(f"Testing {len(layers_to_test)} layers × {len(COEFFICIENTS)} coefficients = {len(layers_to_test) * len(COEFFICIENTS)} configurations")

# Run coefficient sweep
steered_results = sweep_coefficients(
    model=model,
    tokenizer=tokenizer,
    prompts=input_prompts,
    steering_vectors=steering_vectors,
    layers_to_test=layers_to_test,
    coefficients=COEFFICIENTS,
    batch_size=BATCH_SIZE,
    max_new_tokens=MAX_NEW_TOKENS
)

print(f"Generated steered responses for {len(steered_results)} configurations")

# CELL 4: Validate and Analyze Steered Results
print("\n=== CELL 4: Validate and Analyze Steered Results ===")

evaluation_results = {}

for (layer_idx, coeff), steered_responses in tqdm(steered_results.items(), desc="Processing steering configs"):
    print(f"\nProcessing layer {layer_idx}, coefficient {coeff:+.1f}")

    # Create steered prompts (input prompt + steered response)
    steered_prompts = [
        prompt + response
        for prompt, response in zip(input_prompts, steered_responses)
    ]

    # Validate steered responses with DeepSeek to extract answer letters and validation info
    steered_validations = validate_responses(steered_responses, openrouter_client)

    # Extract validation metrics from each validation result
    steered_answers = []
    compliance_labels = []
    completeness_labels = []

    for validation in steered_validations:
        # Extract answer letter, compliance, and completeness
        is_compliant, is_complete, answer_letter = extract_validation_data(validation)

        steered_answers.append(answer_letter)
        compliance_labels.append('compliant' if is_compliant else 'non_compliant')
        completeness_labels.append('complete' if is_complete else 'truncated')

    # Compute accuracy by comparing steered answers to ground truth
    accuracy_labels = []
    correct_count = 0

    for i, orig_item in enumerate(val_unfaithful):
        ground_truth = orig_item.get('ground_truth_letter')
        steered_answer = steered_answers[i]

        is_correct = (steered_answer == ground_truth) if (steered_answer and ground_truth) else False
        accuracy_labels.append('correct' if is_correct else 'incorrect')

        if is_correct:
            correct_count += 1

    # Compute aggregate metrics for this configuration
    accuracy_rate = correct_count / len(val_unfaithful) if val_unfaithful else 0
    compliance_rate = sum(1 for c in compliance_labels if c == 'compliant') / len(compliance_labels) if compliance_labels else 0
    completeness_rate = sum(1 for c in completeness_labels if c == 'complete') / len(completeness_labels) if completeness_labels else 0

    # Store results for this configuration
    evaluation_results[(layer_idx, coeff)] = {
        'steered_responses': steered_responses,
        'steered_prompts': steered_prompts,
        'steered_answers': steered_answers,
        'compliance_labels': compliance_labels,
        'completeness_labels': completeness_labels,
        'accuracy_labels': accuracy_labels,
        'correct_count': correct_count,
        'accuracy_rate': accuracy_rate,
        'compliance_rate': compliance_rate,
        'completeness_rate': completeness_rate,
        'total_prompts': len(val_unfaithful)
    }

    print(f"  Accuracy: {accuracy_rate:.1%} ({correct_count}/{len(val_unfaithful)})")
    print(f"  Compliance: {compliance_rate:.1%}, Completeness: {completeness_rate:.1%}")

print(f"\nProcessed results for {len(evaluation_results)} steering configurations")

# CELL 5: Save Output JSONL and Summary
print("\n=== CELL 5: Save Output JSONL and Summary ===")

# Create output JSONL with ALL configurations
print("Creating output JSONL with all steering configurations...")
output_data = []

for (layer_idx, coeff), results in evaluation_results.items():
    print(f"  Adding records for layer {layer_idx}, coeff {coeff:+.1f}")

    for i, orig_item in enumerate(val_unfaithful):
        record = {
            # Identifiers
            'question_id': orig_item.get('question_id', i),
            'prompt_index': i,

            # Question data
            'question': orig_item.get('question'),
            'choices': orig_item.get('choices'),

            # Input prompt (unannotated)
            'biased_input_prompt': orig_item.get('biased_input_prompt'),
            'hint': orig_item.get('hint'),

            # Steering configuration
            'steering_layer': layer_idx,
            'steering_coefficient': coeff,

            # Steered results
            'steered_response': results['steered_responses'][i],
            'steered_prompt': results['steered_prompts'][i],
            'steered_answer_letter': results['steered_answers'][i],

            # Validation metrics
            'compliance': results['compliance_labels'][i],
            'completeness': results['completeness_labels'][i],

            # Performance metrics
            'accuracy': results['accuracy_labels'][i],

            # Ground truth and reference data
            'ground_truth_letter': orig_item.get('ground_truth_letter'),
            'hint_letter': orig_item.get('hint_letter'),

            # Original faithfulness classification (from input file, always 'unfaithful')
            'original_faithfulness_classification': orig_item.get('faithfulness_classification', 'unfaithful'),

            # Metadata
            'split': 'val',
            'date': TODAY,
            'model': MODEL_ID
        }
        output_data.append(record)

os.makedirs(os.path.dirname(OUTPUT_FILE), exist_ok=True)
save_jsonl(output_data, OUTPUT_FILE)
print(f"Saved {len(output_data)} records to {OUTPUT_FILE}")
print(f"  ({len(evaluation_results)} configurations × {len(val_unfaithful)} examples)")

# Create summary file with aggregated metrics
print("\nCreating summary file...")
end_time = time.time()

summary = {
    'metadata': {
        'date': TODAY,
        'model': MODEL_ID,
        'input_file': INPUT_PROMPTS_FILE,
        'steering_vectors_file': INPUT_VECTORS_FILE,
        'output_file': OUTPUT_FILE,
        'num_examples': len(val_unfaithful),
        'layers_tested': layers_to_test,
        'coefficients_tested': COEFFICIENTS,
        'processing_time_seconds': end_time - start_time
    },
    'all_configurations': {
        f"layer_{layer}_coeff_{coeff:+.1f}": {
            'layer': layer,
            'coefficient': coeff,
            'accuracy_rate': results['accuracy_rate'],
            'correct_count': results['correct_count'],
            'total_prompts': results['total_prompts'],
            'compliance_rate': results['compliance_rate'],
            'completeness_rate': results['completeness_rate']
        }
        for (layer, coeff), results in evaluation_results.items()
    }
}

os.makedirs(os.path.dirname(SUMMARY_FILE), exist_ok=True)
with open(SUMMARY_FILE, 'w', encoding='utf-8') as f:
    json.dump(summary, f, indent=2, ensure_ascii=False)
print(f"Summary saved to {SUMMARY_FILE}")

print(f"\n=== STEERING EVALUATION COMPLETE ===")
print(f"Processing time: {(end_time - start_time) / 60:.2f} minutes")
print(f"\nTested {len(evaluation_results)} configurations on {len(val_unfaithful)} unfaithful examples")
print(f"\nResults saved to:")
print(f"  Data: {OUTPUT_FILE}")
print(f"  Summary: {SUMMARY_FILE}")
print(f"\nNext steps:")
print(f"  - Run eval_faithfulness.py to evaluate faithfulness of steered outputs")
print(f"  - Analyze results to select best configuration for final testing")
