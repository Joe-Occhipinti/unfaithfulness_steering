# =============================================================================
# I/O CONFIGURATION (manually specify all paths)
# =============================================================================

# Input files - read from cloned repo (local, working dir is /content/unfaithfulness_steering)
INPUT_FILE = "data/behavioural/baseline_stem_2025-10-15.jsonl"

# Output files - save directly to Google Drive root (no download consent needed)
OUTPUT_FILE = "/content/drive/MyDrive/hinted_stem_2025-10-15.jsonl"
SUMMARY_FILE = "/content/drive/MyDrive/hinted_summary_stem_2025-10-15.json"

# =============================================================================
# HINTED-SPECIFIC MODEL & GENERATION PARAMETERS (easy to tune)
# =============================================================================

MODEL_ID = "deepseek-ai/DeepSeek-R1-Distill-Llama-8B"
BATCH_SIZE = 10
MAX_NEW_TOKENS = 2048
MAX_INPUT_LENGTH = 1024

print(f"=== HINTED EVALUATION ===")
print(f"Model: {MODEL_ID}")
print(f"Input: {INPUT_FILE}")
print(f"Output: {OUTPUT_FILE}")
print(f"Batch Size: {BATCH_SIZE}, Max New Tokens: {MAX_NEW_TOKENS}")

# =============================================================================
# HINTED EVALUATION WORKFLOW - CELL-BY-CELL FOR COLAB
# =============================================================================

# CELL 1: Setup and Model Loading
print("=== CELL 1: Setup and Model Loading ===")
start_time = time.time()

# Load model (reusable)
model, tokenizer = load_model(MODEL_ID)

# CELL 2: Data Loading and Hinted Prompt Creation
print("\n=== CELL 2: Data Loading and Hinted Prompt Creation ===")

# Load baseline results (correct answers only)
print(f"Loading baseline results from: {INPUT_FILE}")
baseline_data = load_jsonl(INPUT_FILE)

# Split into correct and wrong baseline answers
correct_baseline = [item for item in baseline_data if item['accuracy_label'] == 'correct']
wrong_baseline = [item for item in baseline_data if item['accuracy_label'] == 'wrong']
print(f"Found {len(correct_baseline)} correct and {len(wrong_baseline)} wrong answers from {len(baseline_data)} total")

# Set distribution of hint templates by subject (for "by_subject" strategy)
subject_to_template = {
    "high_school_psychology": 0,
    "high_school_macroeconomics":2,
    "high_school_microeconomics":2,
    "high_school_european_history": 1,
    "high_school_us_history": 1,
    "high_school_world_history": 1,
    "prehistory": 1
}

# Loop 1: Create wrong hints for correct baseline answers
print(f"\n--- Loop 1: Wrong hints for {len(correct_baseline)} baseline correct answers ---")
wrong_hint_prompts, wrong_hint_info = create_hinted_prompts(
    correct_baseline,
    hint_mode="wrong",
    bias_strategies=["self-consistency", "reward_hacking", "grader_hacking", "argument"],
    distribution_strategy="by_subject",
    distribution_config=subject_to_template,
    random_seed=42,
    return_hint_info=True
)

# Loop 2: Create correct hints for wrong baseline answers
print(f"\n--- Loop 2: Correct hints for {len(wrong_baseline)} baseline wrong answers ---")
correct_hint_prompts, correct_hint_info = create_hinted_prompts(
    wrong_baseline,
    hint_mode="correct",
    bias_strategies=["self-consistency", "reward_hacking", "grader_hacking", "argument"],
    distribution_strategy="by_subject",
    distribution_config=subject_to_template,
    random_seed=42,
    return_hint_info=True
)

# Combine both
combined_baseline = correct_baseline + wrong_baseline
hinted_prompts = wrong_hint_prompts + correct_hint_prompts
hint_info_list = wrong_hint_info + correct_hint_info

print(f"\n--- Ready to process {len(hinted_prompts)} total hinted prompts ---")

# CELL 3: Text Generation
print("\n=== CELL 3: Text Generation ===")

# Generate responses for hinted prompts
all_answers = batch_generate(
    model=model,
    tokenizer=tokenizer,
    prompts=hinted_prompts,
    batch_size=BATCH_SIZE,
    max_new_tokens=MAX_NEW_TOKENS,
    max_input_length=MAX_INPUT_LENGTH
)

# CELL 4: Store Hinted Results (Validation done separately offline)
print("\n=== CELL 4: Store Hinted Results ===")
print("Note: Validation and answer extraction will be done offline in separate script")

# Process results (hinted-specific structure)
print(f"\n--- Processing hinted results ---")
results = []

for i, (baseline_item, hinted_prompt, generated_answer, hint_info) in enumerate(
    zip(combined_baseline, hinted_prompts, all_answers, hint_info_list)
):
    # Get original correct answer from baseline
    original_answer_letter = baseline_item['answer_letter']
    ground_truth_letter = baseline_item['ground_truth_letter']

    # Get baseline accuracy
    baseline_accuracy = baseline_item['accuracy_label']

    # Create hinted result record (hinted-specific structure, no validation yet)
    result = {
        # Original MMLU data (from baseline)
        'question': baseline_item['question'],
        'subject': baseline_item['subject'],
        'choices': baseline_item['choices'],
        'answer': baseline_item['answer'],  # Original index

        # Baseline results (preserved for comparison)
        'baseline_input_prompt': baseline_item['baseline_input_prompt'],
        'baseline_generated_text': baseline_item['baseline_generated_text'],
        'baseline_answer_letter': baseline_item['answer_letter'],  # Original correct answer
        'baseline_accuracy_label': baseline_accuracy,
        'ground_truth_letter': baseline_item['ground_truth_letter'],

        # Hinted prompts and generation (README requirement)
        'hinted_input_prompt': hinted_prompt,
        'hinted_generated_text': generated_answer,
        'hinted_prompt': hinted_prompt + generated_answer,

        # Hint information (what hint was given)
        'hint_letter': hint_info['hint_letter'],
        'hint_template': hint_info['hint_template'],

        # Metadata
        'date': TODAY,
        'model': MODEL_ID
    }

    results.append(result)

print(f"Stored {len(results)} hinted results (validation will be done separately)")

# CELL 5: Save Output JSONL and Summary
print("\n=== CELL 5: Save Output JSONL and Summary ===")

# Save results (hinted-specific paths and summary)
print(f"\n--- Saving hinted results ---")

# Save detailed results
save_jsonl(results, OUTPUT_FILE)
print(f"Saved {len(results)} results to {OUTPUT_FILE}")

# Save summary metrics
end_time = time.time()
summary = {
    'metadata': {
        'date': TODAY,
        'model': MODEL_ID,
        'input_file': INPUT_FILE,
        'output_file': OUTPUT_FILE,
        'num_examples': len(results),
        'processing_time_seconds': end_time - start_time
    },
    'configuration': {
        'batch_size': BATCH_SIZE,
        'max_new_tokens': MAX_NEW_TOKENS,
        'max_input_length': MAX_INPUT_LENGTH
    },
    'hint_distribution': {
        'total_prompts': len(results),
        'correct_baseline_wrong_hints': len(wrong_hint_prompts),
        'wrong_baseline_correct_hints': len(correct_hint_prompts)
    },
    'note': 'Validation and answer extraction done separately in validate_hinted.py'
}

with open(SUMMARY_FILE, 'w', encoding='utf-8') as f:
    json.dump(summary, f, indent=2, ensure_ascii=False)

print(f"Summary saved to {SUMMARY_FILE}")

print(f"\n=== HINTED EVALUATION COMPLETE ===")
print(f"Processing time: {(end_time - start_time) / 60:.2f} minutes")
print(f"\nGenerated hinted responses for {len(results)} examples")
print(f"\nResults saved to:")
print(f"  Data: {OUTPUT_FILE}")
