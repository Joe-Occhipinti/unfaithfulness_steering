def load_contrastive_data(jsonl_file):
    """
    Loads contrastive prompts from a JSONL file.
    Expected structure: {"id": 1, "faithfulness": "...", "unfaithfulness": "..."}
    """
    print(f"Loading data from {jsonl_file}...")
    data = []
    with open(jsonl_file, 'r', encoding='utf-8') as f:
        for line in f:
            try:
                record = json.loads(line)
                if 'faithfulness' in record and 'unfaithfulness' in record:
                    data.append(record)
            except json.JSONDecodeError:
                print(f"Skipping malformed line")
    print(f"Loaded {len(data)} pairs.")
    return data

def extract_activations(data, model, tokenizer, device):
    """
    Extracts last token activations for both faithful and unfaithful prompts.
    """
    print("Extracting activations...")
    
    # Structure:
    # {
    #   "faithfulness_prompts": { id: { layer_idx: tensor } },
    #   "unfaithfulness_prompts": { id: { layer_idx: tensor } }
    # }
    dataset = {
        "faithfulness_prompts": {},
        "unfaithfulness_prompts": {}
    }
    
    for item in tqdm(data, desc="Processing prompts"):
        item_id = item.get('id')
        
        # Process both types
        for key in ['faithfulness', 'unfaithfulness']:
            text = item[key]
            
            # Tokenize
            inputs = tokenizer(text, return_tensors="pt").to(device)
            
            # Forward pass
            with torch.no_grad():
                outputs = model(**inputs, output_hidden_states=True)
            
            # Extract activations
            # outputs.hidden_states is a tuple of (layer_0, layer_1, ..., layer_N)
            layer_activations = {}
            for layer_idx, layer_tensor in enumerate(outputs.hidden_states):
                # Extract last token activation: [0, -1, :]
                # Move to CPU immediately to save GPU memory
                activation = layer_tensor[0, -1, :].cpu()
                
                # Store
                layer_activations[layer_idx] = activation
            
            # Add to dataset
            target_dict = dataset[f"{key}_prompts"]
            target_dict[item_id] = layer_activations
            
    return dataset

def compute_vectors(dataset):
    """
    Computes steering vectors: Mean(Faithful) - Mean(Unfaithful).
    Discards Layer 0 (Embeddings) and shifts indices (Layer 1 -> 0).
    """
    print("Computing steering vectors...")
    
    faithful_dict = dataset["faithfulness_prompts"]
    unfaithful_dict = dataset["unfaithfulness_prompts"]
    
    # Get all layer indices from the first item
    first_id = next(iter(faithful_dict))
    all_layers = sorted(faithful_dict[first_id].keys())
    
    steering_vectors = {}
    layer_stats = {}
    
    for layer_idx in all_layers:
        # Skip Layer 0 (Embeddings)
        if layer_idx == 0:
            continue
            
        # Collect all vectors for this layer
        f_vectors = [d[layer_idx] for d in faithful_dict.values()]
        u_vectors = [d[layer_idx] for d in unfaithful_dict.values()]
        
        if not f_vectors or not u_vectors:
            continue
            
        # Stack and mean
        f_tensor = torch.stack(f_vectors)
        u_tensor = torch.stack(u_vectors)
        
        f_mean = f_tensor.mean(dim=0)
        u_mean = u_tensor.mean(dim=0)
        
        # Difference
        vector = f_mean - u_mean
        
        # Shift index: Layer 1 -> 0
        new_layer_idx = layer_idx - 1
        steering_vectors[new_layer_idx] = vector
        
        layer_stats[new_layer_idx] = {
            "original_layer": layer_idx,
            "vector_norm": vector.norm().item(),
            "faithful_norm": f_mean.norm().item(),
            "unfaithful_norm": u_mean.norm().item()
        }
        
    return steering_vectors, layer_stats

