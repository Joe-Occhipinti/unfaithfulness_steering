# MAIN EXECUTION
# =============================================================================

def main():
    # Setup
    device = "cuda" if torch.cuda.is_available() else "cpu"
    print(f"Using device: {device}")
    
    # Ensure output directory exists
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    
    # Load Data
    if not os.path.exists(INPUT_FILE):
        print(f"Error: Input file not found at {INPUT_FILE}")
        print("Please check the path in Google Drive.")
        return

    data = load_contrastive_data(INPUT_FILE)
    if not data:
        print("No data found. Exiting.")
        return

    # Load Model
    print(f"Loading model: {MODEL_ID}")
    tokenizer = AutoTokenizer.from_pretrained(MODEL_ID)
    model = AutoModelForCausalLM.from_pretrained(
        MODEL_ID, 
        torch_dtype=torch.float16 if device == "cuda" else torch.float32,
        device_map="auto" if device == "cuda" else None
    )
    model.eval()
    
    # Extract
    activations_dataset = extract_activations(data, model, tokenizer, device)
    
    # Save Activations
    activations_file = os.path.join(OUTPUT_DIR, "activations_dataset.pkl")
    print(f"Saving activations to {activations_file}...")
    with open(activations_file, 'wb') as f:
        pickle.dump(activations_dataset, f)
        
    # Compute Vectors
    steering_vectors, layer_stats = compute_vectors(activations_dataset)
    
    # Save Vectors
    vectors_file = os.path.join(OUTPUT_DIR, "steering_vectors.pkl")
    
    output_data = {
        "steering_vectors": steering_vectors,
        "computation_stats": {
            "layer_stats": layer_stats,
            "sample_count": len(data)
        },
        "metadata": {
            "description": "Contrastive steering vectors (Faithful - Unfaithful)",
            "source_file": INPUT_FILE,
            "model": MODEL_ID,
            "computation_date": datetime.now().isoformat()
        }
    }
    
    print(f"Saving steering vectors to {vectors_file}...")
    with open(vectors_file, 'wb') as f:
        pickle.dump(output_data, f)
        
    print("Done!")
    print(f"Results saved to Drive: {OUTPUT_DIR}")

if __name__ == "__main__":
    main()
